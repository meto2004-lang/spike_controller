  var lang = "ar";

  function format(template, params) {
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, function (match, name) {
      return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match;
    });
  }

  function t(key, params, fallback) {
    var table = dictionary[lang] || dictionary.ar;
    var value = table[key];
    if (value === undefined) value = dictionary.en[key];
    if (value === undefined) return fallback === undefined ? key : fallback;
    return format(value, params);
  }

  function apply(root) {
    var scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.textContent = t(node.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (node) {
      node.setAttribute("title", t(node.getAttribute("data-i18n-title")));
      if (!node.hasAttribute("aria-label")) node.setAttribute("aria-label", t(node.getAttribute("data-i18n-title")));
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach(function (node) {
      node.setAttribute("placeholder", t(node.getAttribute("data-i18n-ph")));
    });
  }

  function setLang(next) {
    if (!dictionary[next]) next = "ar";
    lang = next;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.title = lang === "ar"
      ? "Hyena Control — محرر SPIKE Prime"
      : "Hyena Control — SPIKE Prime IDE";
    apply(document);
  }

  window.I18N = {
    t: t,
    apply: apply,
    setLang: setLang,
    get lang() { return lang; },
    dictionary: dictionary
  };
